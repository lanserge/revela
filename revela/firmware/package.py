"""Package the firmware as modules a picam2hdmi bridge loads.

Each part of the firmware is its own module: the core (the actions of
revela_fw.h, the one writer of the ISP and the display), and AE, AWB and
AF, each optional. The core is fixed C beside one generated header,
core_map.h, which is everything that varies between builds -- the ISP's
register map, the design's own settings, every block's ID word, the
display raster's fields -- cut from the build's maps at export, so the
device parses nothing. On a Pi the core module also carries the
platform's half: platform/pi, the HAL over the bridge and the bridge's
hooks turned into the firmware's actions.

    python -m revela.firmware.package core --regmap R --cable-map C \\
        [--profile P] --out revela-core.tar.gz
    python -m revela.firmware.package ae --out revela-ae.tar.gz
    python -m revela.firmware.package sensor --sensor ov5647 \
        [--profile REF] --out sensor-ov5647.tar.gz
"""
from __future__ import annotations

import argparse
import io
import json
import re
import sys
import tarfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADERS = ("revela_hal.h", "revela_fw.h", "revela_algo.h", "revela_sensor.h")
LOOPS = ("ae", "awb", "af")
RASTER = "scanout_regs"         # the cable map's display raster file
RASTER_FIELDS = ("clk_sel", "ps_per_px", "h_total", "h_active", "hs_beg", "hs_end", "v_total",
                 "v_active", "vs_beg", "vs_end", "hs_pos", "vs_pos",
                 "win_x0", "win_y0", "center", "arm")


def api(header: str, name: str) -> str:
    """A contract's version: the number its header states, and a digest of
    that header and every firmware header it includes. The number says
    what the contract means; the digest is the layout two sides compile
    against -- a struct that moved, under a number nobody bumped, is a
    different contract, and a module built on the old one is refused
    instead of reading the new layout at the old offsets."""
    m = re.search(rf"#define {name} (\d+)", (HERE / header).read_text())
    return f"{int(m.group(1))}-{_headers_digest(header)}"


def _headers_digest(header: str) -> str:
    import hashlib
    seen, order, todo = set(), [], [header]
    while todo:
        h = todo.pop(0)
        if h in seen or not (HERE / h).exists():
            continue
        seen.add(h)
        order.append(h)
        todo += re.findall(r'#include "([^"]+)"', (HERE / h).read_text())
    digest = hashlib.sha256()
    for h in sorted(order):
        digest.update(h.encode() + b"\0" + (HERE / h).read_bytes())
    return digest.hexdigest()[:12]


def scoped_rows(regmap: dict) -> list[tuple[str, int, int]]:
    """Every register as each composite containing it names it:
    ``<composite ref>/<path relative to the instance>``. A composite
    instanced twice gives a key two rows, and a profile for it lands in
    both."""
    rows = []
    for c in regmap.get("composites", []):
        prefix = c["path"] + "." if c["path"] else ""
        for b in regmap["blocks"]:
            for r in b["registers"]:
                key = f"{b['path']}.{r['name']}"
                if key.startswith(prefix):
                    rows.append((f"{c['block']}/{key[len(prefix):]}",
                                 r["address"], r["bits"]))
    return rows


def core_map_h(regmap: dict, cable_map: dict,
               design: dict | None = None) -> str:
    """Everything the core needs of one build, as C."""
    isp_base = cable_map["isp"]["base"]
    rows = [(f"{b['path']}.{r['name']}", isp_base + r["address"], r["bits"])
            for b in regmap["blocks"] for r in b["registers"]]
    where = {k: (a, bits) for k, a, bits in rows}
    design = design or {}
    unknown = sorted(set(design) - set(where))
    if unknown:
        raise ValueError(f"design values for registers this map does not "
                         f"have: {unknown}")
    raster = cable_map[RASTER]
    missing = [f for f in (*RASTER_FIELDS, "id") if f not in raster["registers"]]
    if missing:
        raise ValueError(f"{RASTER} in the cable map has no {missing}")
    commit = regmap["control"]["commit_register"]

    L = ["/* generated by revela.firmware.package from the build's maps "
         "-- do not edit */",
         "#ifndef REVELA_CORE_MAP_H", "#define REVELA_CORE_MAP_H",
         "#include <stdint.h>", "",
         "struct revela_reg { const char *key; uint32_t addr; uint8_t bits; };",
         "",
         "/* the ISP's parameters by name */",
         "static const struct revela_reg REVELA_MAP[] = {"]
    L += [f'    {{ "{k}", 0x{a:04X}u, {bits} }},'
          for k, a, bits in sorted(rows, key=lambda x: x[1])]
    L += ["};",
          "#define REVELA_MAP_N (sizeof REVELA_MAP / sizeof REVELA_MAP[0])",
          "",
          "/* the same registers as each composite containing them names "
          "them: where a sensor profile's keys land */",
          "static const struct revela_reg REVELA_SCOPED[] = {"]
    L += [f'    {{ "{k}", 0x{isp_base + a:04X}u, {bits} }},'
          for k, a, bits in sorted(scoped_rows(regmap),
                                   key=lambda x: (x[1], x[0]))]
    L += ["    { 0, 0, 0 },", "};", "",
          "/* the design's own settings, resolved at export */",
          "static const struct { uint32_t addr; uint8_t bits; int32_t value; }",
          "REVELA_DESIGN[] = {"]
    L += [f"    {{ 0x{where[k][0]:04X}u, {where[k][1]}, {v} }},  /* {k} */"
          for k, v in design.items()]
    L += ["    { 0, 0, 0 },", "};", "",
          "/* every ID word, read before anything is written */",
          "static const struct { const char *path; uint32_t addr; "
          "uint32_t value; }",
          "REVELA_IDS[] = {"]
    for b in regmap["blocks"]:
        iv = b["id_version"]
        L.append(f'    {{ "{b["path"]}", 0x{isp_base + iv["address"]:04X}u, '
                 f'0x{iv["value"]:08X}u }},')
    L.append(f'    {{ "the display raster", '
             f'0x{raster["base"] + raster["registers"]["id"]:04X}u, '
             f'0x{raster["id"]:08X}u }},')
    L += ["    { 0, 0, 0 },", "};", ""]
    L.append(f"#define REVELA_COMMIT 0x{where[commit][0]:04X}u")
    if "pipe.bayer_phase" in where:
        L.append(f"#define REVELA_BAYER_PHASE "
                 f"0x{where['pipe.bayer_phase'][0]:04X}u")
    else:
        L.append("/* no Bayer phase register: this build's phase rides "
                 "its stream */")
    L.append(f"#define REVELA_ISP_KHZ {int(cable_map['isp']['clock_khz'])}u")
    L.append(f"#define REVELA_ISP_WIDTH {int(regmap['geometry']['width'])}u")
    L.append(f"#define REVELA_ISP_HEIGHT {int(regmap['geometry']['height'])}u")
    # the crop, where the build carries one: the window the picture is
    crops = [b["path"] for b in regmap["blocks"] if b["block"] == "crop"]
    if len(crops) > 1:
        raise ValueError(f"this build carries {len(crops)} crops ({crops}); "
                         "the firmware sets one")
    for f in ("x0", "y0", "w", "h") if crops else ():
        L.append(f"#define REVELA_CROP_{f.upper()} "
                 f"0x{where[crops[0] + '.' + f][0]:04X}u")
    # the mark, where the build carries one: its placement registers, and
    # the corner rule's inset, which is the block's
    marks = [b["path"] for b in regmap["blocks"] if b["block"] == "logo"]
    if len(marks) > 1:
        raise ValueError(f"this build carries {len(marks)} marks ({marks}); "
                         "the firmware places one")
    if marks:
        from revela.blocks.logo import INSET
        L.append(f"#define REVELA_LOGO_X0 0x{where[marks[0] + '.x0'][0]:04X}u")
        L.append(f"#define REVELA_LOGO_Y0 0x{where[marks[0] + '.y0'][0]:04X}u")
        L.append(f"#define REVELA_LOGO_INSET {INSET}u")
    L.append(f"#define REVELA_RASTER_BASE 0x{raster['base']:04X}u")
    # Every field of the display's file by name, for set and get: the
    # file keeps each field's own bits, so a row needs no width of its own.
    L += ["/* the display raster's fields by name: raster.<field> */",
          "static const struct revela_reg REVELA_RASTER_MAP[] = {"]
    L += [f'    {{ "raster.{name}", 0x{raster["base"] + off:04X}u, 32 }},'
          for name, off in sorted(raster["registers"].items(),
                                  key=lambda kv: kv[1]) if name != "id"]
    L += ["};", "#define REVELA_RASTER_MAP_N "
          "(sizeof REVELA_RASTER_MAP / sizeof REVELA_RASTER_MAP[0])"]
    for f in RASTER_FIELDS:
        L.append(f"#define REVELA_R_{f.upper()} "
                 f"0x{raster['base'] + raster['registers'][f]:04X}u")
    xb, yb = raster["counter_bits"]
    clocks = raster["clocks"]
    L += ["/* the display's clocks, row by row of its clock select: each with",
          " * the fine steps its pixel is and its serializer MMCM's recipe */",
          "static const struct { uint32_t khz, ps_per_px, divclk, mult, out0; }",
          "REVELA_CLOCKS[] = {"]
    L += [f"    {{ {int(c['khz'])}u, {int(c['ps_per_px'])}u, "
          f"{int(c['pll']['divclk'])}u, {int(c['pll']['mult'])}u, "
          f"{int(c['pll']['out0'])}u }}," for c in clocks]
    L += ["};", f"#define REVELA_N_CLOCKS {len(clocks)}u"]
    if "tmds_pll" in cable_map:
        L.append(f"#define REVELA_PLL_BASE 0x{cable_map['tmds_pll']['base']:04X}u")
    L += [
          f"#define REVELA_RASTER_XB {int(xb)}u",
          f"#define REVELA_RASTER_YB {int(yb)}u", "", "#endif"]
    return "\n".join(L) + "\n"


def _tar(out: Path, files: dict) -> None:
    with tarfile.open(out, "w:gz") as tar:
        for name, data in files.items():
            b = data.encode() if isinstance(data, str) else data
            info = tarfile.TarInfo(name)
            info.size = len(b)
            info.mtime = int(time.time())
            tar.addfile(info, io.BytesIO(b))


def _manifest(name, slot, version, sources, provides=(), requires=()):
    return json.dumps({"name": name, "version": version,
                       "kind": "picam2hdmi-module", "abi": 1, "slot": slot,
                       "provides": list(provides),
                       "requires": list(requires),
                       "sources": list(sources)}, indent=2) + "\n"


def core_package(regmap: dict, cable_map: dict, design: dict | None,
                 version: str) -> dict:
    """The core, for the Pi: its fixed C, its build's map, the contract
    headers, and the Pi's platform half."""
    sources = ["core.c", "pi_glue.c"]
    return {
        "manifest.json": _manifest(
            "revela-core", "isp", version, sources,
            provides=[f"revela-algo-api:{api('revela_algo.h', 'REVELA_ALGO_API')}",
                      f"revela-sensor-api:"
                      f"{api('revela_sensor.h', 'REVELA_SENSOR_API')}"]),
        "core.c": (HERE / "core" / "core.c").read_text(),
        "core_map.h": core_map_h(regmap, cable_map, design),
        "pi_glue.c": (HERE / "platform" / "pi" / "pi_glue.c").read_text(),
        **{h: (HERE / h).read_text() for h in HEADERS},
        # the maps ride the package verbatim: the panel renders its
        # controls from the regmap, and core_map.h was cut from both
        "regmap.json": json.dumps(regmap, indent=2) + "\n",
        "cable_map.json": json.dumps(cable_map, indent=2) + "\n",
    }


def loop_package(loop: str, version: str) -> dict:
    """One 3A module: its own C and the contract headers it is built to."""
    source = f"{loop}.c"
    return {
        "manifest.json": _manifest(
            f"revela-{loop}", loop, version, [source],
            requires=[f"revela-algo-api:"
                      f"{api('revela_algo.h', 'REVELA_ALGO_API')}"]),
        source: (HERE / loop / source).read_text(),
        **{h: (HERE / h).read_text() for h in HEADERS},
    }


def sensor_facts_c(description: dict | None) -> list:
    """The sensor's laws, as revela_sensor.h's struct.

    Read from the sensor description -- the same file the host loads --
    so the number a loop uses and the number a test uses are one number.
    Absent description, absent struct: a sensor that does not state its
    laws says so with NULL rather than with plausible defaults, because a
    guessed gain law is an exposure loop that converges on the wrong
    brightness and never says why.
    """
    if not description:
        return []
    gain = description.get("gain", {}).get("analogue", {})
    coarse = description.get("exposure", {}).get("coarse", {})
    delays = description.get("apply_delay_frames", {})
    if gain.get("model") != "linear":
        # only the parameterised linear law survives the trip to C; a
        # part with another law needs the contract to grow
        return []
    frame = int(description.get("timing", {}).get("frame_length_lines", 0))
    return [
        "static const struct revela_sensor_facts facts = {",
        f"    .gain_unity_code = {int(gain.get('unity_code', 0))},",
        f"    .gain_min_code = {int(gain.get('code_min', 0))},",
        f"    .gain_max_code = {int(gain.get('code_max', 0))},",
        f"    .exposure_min_lines = {int(coarse.get('min', 0))},",
        f"    .exposure_max_margin = {int(coarse.get('max_margin', 0))},",
        f"    .integration_default_lines = "
        f"{max(int(coarse.get('min', 0)), frame - int(coarse.get('max_margin', 0)))},",
        f"    .delay_exposure = {int(delays.get('exposure', 0))},",
        f"    .delay_analog_gain = {int(delays.get('analogue_gain', 0))},",
        f"    .delay_digital_gain = {int(delays.get('digital_gain', 0))},",
        f"    .black_level = "
        f"{int(description.get('black_level', {}).get('pedestal', 0))},",
        "};",
        "",
    ]


def sensor_modes_c(description: dict | None) -> list:
    """The sensor's modes, as revela_sensor.h's table: each with the frame
    it delivers, its default timing and the register writes that select it,
    all read from the sensor description. Absent description, no table."""
    from revela.blocks.context import BAYER_ORDER_CODES
    if not description or not description.get("modes"):
        return []
    native = description["cfa"]["order"]
    bits = int(description["format"]["bit_depth"])
    sequences = description.get("register_sequences", {})
    L = []
    for i, m in enumerate(description["modes"]):
        writes = sequences.get(m.get("register_sequence", ""), {}).get(
            "writes", [])
        L.append(f"static const struct revela_sensor_write mode{i}_writes[] = {{")
        L += [f"    {{ 0x{w['address']:04X}, 0x{w['value']:02X} }},"
              + (f"  /* {w['comment']} */" if w.get("comment") else "")
              for w in writes]
        L += ["    { 0, 0 },", "};"]
    L.append("static const struct revela_sensor_mode modes[] = {")
    for i, m in enumerate(description["modes"]):
        n = len(sequences.get(m.get("register_sequence", ""), {}).get(
            "writes", []))
        phase = BAYER_ORDER_CODES[m.get("cfa_order", native)]
        L.append(f'    {{ "{m["name"]}", {m["width"]}, {m["height"]}, {bits}, '
                 f'{phase}, {m.get("pixel_rate_hz", 0)}, '
                 f'{m.get("line_length_pck", 0)}, '
                 f'{m.get("frame_length_lines", 0)}, mode{i}_writes, {n} }},')
    L += ["};", ""]
    return L


def sensor_c(sensor: str, values: dict, description: dict | None) -> str:
    """A sensor module: its facts, its modes and its fitted profile, as
    data."""
    L = [f"/* generated by revela.firmware.package -- the {sensor} module:",
         " * its laws, its modes and its fitted ISP profile, as data; it",
         " * drives nothing itself */",
         "#include <stdint.h>", '#include "revela_sensor.h"', "",
         "static const struct revela_profile_entry profile[] = {"]
    L += [f'    {{ "{k}", {v} }},' for k, v in values.items()]
    L += ["    { 0, 0 },", "};", ""]
    facts = sensor_facts_c(description)
    L += facts
    modes = sensor_modes_c(description)
    L += modes
    n_modes = len(description["modes"]) if modes else 0
    L += ["static const struct revela_sensor s = {",
          "    .api = REVELA_SENSOR_API,", f'    .name = "{sensor}",',
          "    .profile = profile,",
          f"    .facts = {'&facts' if facts else '0'},",
          f"    .modes = {'modes' if modes else '0'}, .n_modes = {n_modes},",
          "};", "",
          "const struct revela_sensor *revela_sensor(void) { return &s; }"]
    return "\n".join(L) + "\n"


def sensor_package(sensor: str, ref: str | None, version: str) -> dict:
    from np2hw.design import profile
    fitted = profile.resolve(ref or
                             f"revela.sensors.{sensor}.profile:{sensor}")
    values = {f"{fitted.for_ref}/{k}": v
              for k, v in profile.relative(fitted).items()}
    description = None
    if (HERE.parent / "sensors" / sensor / "sensor.json").exists():
        from revela import sensors
        description = sensors.load(sensor)
    source = f"sensor_{sensor}.c"
    return {
        "manifest.json": _manifest(
            f"sensor-{sensor}", "sensor", version, [source],
            requires=[f"revela-sensor-api:"
                      f"{api('revela_sensor.h', 'REVELA_SENSOR_API')}"]),
        source: sensor_c(sensor, values, description),
        "revela_sensor.h": (HERE / "revela_sensor.h").read_text(),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("part", choices=("core", "sensor", *LOOPS))
    parser.add_argument("--sensor", help="the sensor's name (sensor)")
    parser.add_argument("--regmap", help="the ISP's register map (core)")
    parser.add_argument("--cable-map", help="the board's cable_map.json (core)")
    parser.add_argument("--profile", default=None,
                        help="the design's own settings: a profile for the "
                             "design (package.module:name), baked in")
    parser.add_argument("--library", action="append", metavar="DIR")
    parser.add_argument("--version", default="0.1")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    if args.part == "core":
        if not (args.regmap and args.cable_map):
            parser.error("the core is cut from --regmap and --cable-map")
        regmap = json.loads(Path(args.regmap).read_text())
        cable_map = json.loads(Path(args.cable_map).read_text())
        design = {}
        if args.profile:
            from np2hw.design import profile
            from np2hw.design.composite import add_libraries
            add_libraries(args.library)
            design = profile.flatten(profile.resolve(args.profile), regmap)
        files = core_package(regmap, cable_map, design, args.version)
    elif args.part == "sensor":
        if not args.sensor:
            parser.error("a sensor module is cut for --sensor")
        from np2hw.design.composite import add_libraries
        add_libraries(args.library)
        files = sensor_package(args.sensor, args.profile, args.version)
    else:
        files = loop_package(args.part, args.version)
    _tar(Path(args.out), files)
    print(f"{args.out}: revela-{args.part} {args.version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
