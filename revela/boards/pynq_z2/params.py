"""Generate the block design's parameters, from the files that own them.

The block design used to learn its numbers three ways: environment
variables, Tcl defaults beside them, and constants written into the
script. All three agreed, until the depth moved and they did not -- and
the failure a disagreement produces here is not an error but a picture,
because a width mismatch in a block design is a CRITICAL WARNING and a
silent connection of the low bits.

So the numbers are generated, from these owners and no others:

  pipeline.json   THE DESIGN. What the ISP is, independent of any board.
  board.json      THE TARGET. What this silicon is, independent of any
                  design; the jacks are the board's primitives
                  (hdmi_in, hdmi_out), each owning its own facts.
  <isp>_build.json
                  THE DELIVERABLE'S CONTRACT. What the ISP actually
                  traced -- its boundary widths and its latency -- which
                  nobody may restate, because the ISP is the deliverable
                  and this board is the harness testing it. A harness
                  that writes down the interface it is testing will pass
                  after the interface changes.

Everything else -- which raster to drive, whether to build the capture
path -- is THIS BUILD's choice, recorded in design.json, and checked
against what the board says is possible.

    python3 -m revela.boards.pynq_z2.params --out <build dir>

Writes <build dir>/generated/params.tcl, which bd.tcl sources. bd.tcl reads no
environment and declares no defaults; a fact it needs and this file does
not set is an error at once, not a wrong picture twenty minutes later.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

from revela.boards.pynq_z2 import constraints, primitive  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, type=Path,
                        help="the build directory: the ISP's contract is "
                             "read from its hdl/, params.tcl is written "
                             "to its generated/")
    parser.add_argument("--design", type=Path, default=HERE / "pipeline.json")
    args = parser.parse_args()

    board_name = HERE.name
    board = json.loads((HERE / "board.json").read_text())
    design = json.loads(args.design.read_text())
    # THIS BUILD's choices, from the file that owns them. They used to be
    # shell defaults, which meant the bitstream on the bench corresponded
    # to an environment nobody recorded; now a variant build is a diff.
    choices = json.loads((HERE / "design.json").read_text())["build"]
    mode = choices["mode"]
    capture = bool(choices["capture"])

    # The deliverable's own report. Generated by `revela generate`, so it
    # exists only after the ISP has been built -- which is the point: the
    # harness cannot state the ISP's widths before the ISP has traced
    # them.
    contract_path = args.out / "hdl" / f"{design['name']}_build.json"
    if not contract_path.exists():
        return fail(f"{contract_path.name} is missing: generate the ISP "
                    "before its parameters, because its boundary is "
                    "traced, not declared")
    contract = json.loads(contract_path.read_text())

    # CAPABILITY vs CHOICE. The board says what is possible here; the
    # build says what it wants. Asking for what the board cannot do is
    # refused now, by the file that knows, rather than by a cascade of
    # Tcl errors inside Vivado.
    if capture and not board.get("capture", False):
        return fail(f"board {board_name} cannot host the capture path "
                    f"({board.get('capture_note', 'see board.json')})")

    from np2hw.video_out import mode_timing
    try:
        timing = mode_timing(mode)
    except Exception as exc:                        # the table refuses by name
        return fail(f"mode {mode!r}: {exc}")
    out_mhz = float(timing["pixel_mhz"])
    tx_max = float(primitive("hdmi_out")["max_pixel_mhz"])
    if out_mhz > tx_max:
        return fail(f"mode {mode} needs {out_mhz:g} MHz but {board_name}'s "
                    f"hdmi_out is built for {tx_max:g}")

    # The raster the EDID invites a source to send. Nothing here consumes
    # it -- the receiver learns the frame from the header -- but a source
    # that honours it would be asked for this clock, and asking for one
    # the frontend cannot lock is a real fault hiding inside a decoration.
    link_mode = choices["link_mode"]
    try:
        link_mhz = float(mode_timing(link_mode)["pixel_mhz"])
    except Exception as exc:
        return fail(f"link_mode {link_mode!r}: {exc}")
    rx_max = float(primitive("hdmi_in")["max_link_mhz"])
    if link_mhz > rx_max:
        return fail(f"link_mode {link_mode} advertises {link_mhz:g} MHz in "
                    f"the EDID but {board_name}'s hdmi_in is constrained to "
                    f"{rx_max:g}; a source honouring it would send a clock "
                    "this receiver cannot lock")

    # The one boundary the ISP declares (its input) and the one it traces
    # (its output). Both come from the contract; neither is written here.
    boundary = contract["boundary"]
    in_name = next(iter(boundary["inputs"]))
    out_name = next(iter(boundary["outputs"]))
    isp_in = boundary["inputs"][in_name]
    isp_out = boundary["outputs"][out_name]

    # ONE sample width, not two. The stream reaching the ISP is one
    # sample per beat, so the ISP's input width IS the width every block
    # carrying it is built at -- the receiver, both rx_axis shims, the
    # unpacker and the shim's own input port. It was briefly emitted a
    # second time under a name of its own, which turned one fact into a
    # pair that had to be kept equal, and then into a check to keep them
    # equal. The pair was the bug; this is the fix.
    if int(isp_in.get("channels", 1)) != 1:
        return fail(f"the ISP's input {in_name} declares "
                    f"{isp_in['channels']} channels, but everything "
                    "carrying the stream to it is built one sample wide")
    sample_bits = int(isp_in["data_bits"])

    lines = [
        "# GENERATED by revela.boards.pynq_z2.params -- do not edit.",
        "#",
        "# Every number here has exactly one owner, named beside it. If a",
        "# value looks wrong, the fix is in its owner, never in this file",
        "# and never in bd.tcl.",
        "",
        "# --- the target: revela/boards/%s/board.json" % board_name,
        f"set p_part           {board['part']}",
        f"set p_board_part     {board['board_part']}",
        f"set p_ps_clk_mhz     {board['ps_clk_mhz']}",
        "",
        "# --- the deliverable's traced contract: %s" % contract_path.name,
        "# The ISP is what is being tested here; these are ITS numbers,",
        "# read from what it published rather than written down again.",
        "# The sample width is the first of them: the blocks that carry",
        "# the stream to the ISP are built to what the ISP accepts.",
        f"set p_sample_bits    {sample_bits}",
        f"set p_isp_width      {int(contract['geometry']['width'])}",
        f"set p_isp_out_bits   {int(isp_out['data_bits'])}",
        f"set p_isp_channels   {int(isp_out.get('channels', 1))}",
        f"set p_isp_chan_bits  {int(isp_out.get('channel_bits', 0))}",
        f"set p_isp_latency    {int(contract['latency'])}",
        f"set p_isp_toplevel   {contract['toplevel']}",
        "",
        "# --- this build's choices, checked against the board above",
        f"set p_out_mhz        {out_mhz:g}",
        # A 74.25-class raster genlocks; a 148.5-class one free-runs.
        # Derived, so the two can never be set to disagree.
        f"set p_genlock        {1 if out_mhz < 100 else 0}",
        f"set p_capture        {int(capture)}",
        "",
        "# --- the constraints: the design's own, then each primitive's",
        "set p_xdc [list " + " ".join("{%s}" % c for c in constraints()) + "]",
        "",
    ]
    # Into the build directory, never beside board.json: what is
    # generated and what is source do not share a folder, and the board's
    # sources ship inside the revela package, where nothing is written.
    out_dir = args.out / "generated"
    out_dir.mkdir(exist_ok=True)
    out = out_dir / "params.tcl"
    out.write_text("\n".join(lines))
    print(f"generated {out} -- "
          f"{sample_bits}-bit into the ISP, {isp_out['data_bits']}-bit out "
          f"({isp_out.get('channels')} x {isp_out.get('channel_bits')}), "
          f"{mode} at {out_mhz:g} MHz"
          + (", genlocked" if out_mhz < 100 else ", free-running")
          + (", capture" if capture else ""))
    return 0


def fail(message: str) -> int:
    print(f"params.py: {message}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
