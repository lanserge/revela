# The PYNQ-Z2 build, in the order it has to happen.
#
# What a model or a setting decides -- the receiver's format table, the
# ISP, the display raster -- is GENERATED here and never committed, so a
# build that skips a step fails on a missing file, which is the correct
# failure and the reason this script exists. What only takes a width or
# a depth is a Verilog file, read where it ships.
#
# Run it from the directory the build should land in; everything it
# generates, and the Vivado project, goes under build/pynq_z2 there
# (OUT= overrides). The sources beside this script are only read.
#
#   ~/projects/vivado-docker/fpga-build.sh ~/projects/revela \
#       revela/boards/pynq_z2/build.sh
#
# The design is revela.boards.pynq_z2.pynq_demo, JSON through and
# through; its block design is GENERATED from it. A variant build is an
# EDIT to its parameters, not an environment variable: a different raster
# is a different design, and this way the bitstream corresponds to
# something you can diff.
#
# Needs: vivado on PATH; python3 with revela, np2hw, bayerlink and
# bayerlink_fpga importable; and the two vendor trees, found at
# ./board-files and ./vivado-library unless BOARD_FILES= and
# VIVADO_LIBRARY= say otherwise:
#
#   git clone --depth 1 https://github.com/Digilent/vivado-library.git
#   git clone --depth 1 https://github.com/xupsh/pynq-supported-board-file.git board-files
# Stop at the first failure however this is invoked: `sh build.sh`
# ignores the -e on the first line, and a check that fails without
# stopping the build is a check that does not exist.
set -e
here=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-$PWD/build/pynq_z2}
BOARD_FILES=${BOARD_FILES:-$PWD/board-files}
VIVADO_LIBRARY=${VIVADO_LIBRARY:-$PWD/vivado-library}
for tree in "$BOARD_FILES" "$VIVADO_LIBRARY"; do
    [ -d "$tree" ] || { echo "build.sh: $tree is missing; see the header" >&2; exit 1; }
done
mkdir -p "$OUT/generated" "$OUT/hdl"
OUT=$(cd "$OUT" && pwd)

read_build() { python3 -c "import sys; from revela.boards.pynq_z2 import choices; print(choices()[sys.argv[1]])" "$1"; }
# The ISP this design builds, by reference: its geometry and depth are
# stated on its input port, where the stream enters.
ISP=$(python3 -c "from revela.boards.pynq_z2 import isp_ref; print(isp_ref())")
# 155, not 148.5: cutting for a few MHz more than the clock will run
# is what makes the cut placement DETERMINISTIC -- at exactly 148.5
# the estimator's 70ps of optimism decided whether a register moved,
# and builds swung +0.16 to -0.54 on nothing. Generation margin, the
# same idea as timing margin, one stage earlier. (Measured: +0.196
# MET, repeatably, on the build this default comes from.)
ISP_MHZ=$(read_build isp_mhz)

# Where the block design finds what is not beside it. Written first, so
# every later step reads the same answer.
python3 - "$OUT" "$BOARD_FILES" "$VIVADO_LIBRARY" <<'EOF'
import sys, pathlib
out, board_files, vivado_library = sys.argv[1:]
(pathlib.Path(out) / "generated" / "paths.tcl").write_text(
    "# GENERATED by build.sh -- do not edit.\n"
    f"set p_board_files    {{{board_files}}}\n"
    f"set p_vivado_library {{{vivado_library}}}\n")
EOF

echo "== ISP proved (its RTL against its models, word for word), and its pack"
# The board builds the ISP itself, as a node of its design, when the block
# design loads it. This proves the same composite at the same clock first
# and writes its deliverable -- the FuseSoC pack, register map and docs --
# beside the build, so a pack that does not verify stops the build here.
python3 -m np2hw pipeline generate "$ISP" --out "$OUT/isp" --clock-mhz "$ISP_MHZ"

echo "== block design (generated from pynq_demo: the ISP and every generated leaf built with it)"
# Loading the design builds the ISP inside it; the ISP's widths reach the
# blocks around it as the design's own parameters, assigned from the ISP's
# facts. Every wire between our own modules is checked against the ports
# each states, at this build's parameters -- a block design would connect
# the low bits of a mismatch and call it a warning.
python3 -m revela.boards.pynq_z2.blockdesign --out "$OUT"

if [ -n "$NO_VIVADO" ]; then
    echo "NO_VIVADO set: generated and checked, stopping before Vivado"
    exit 0
fi

echo "== implementation"
cd "$OUT"
vivado -mode batch -source "$OUT/generated/rtl.tcl" -tclargs "$OUT"
# Every described vendor block against the pins the tool built for it:
# a description that is not true stops the build before synthesis.
python3 -m np2hw.toolchain.vivado.vendor_check "$OUT"
vivado -mode batch -source "$here/impl_a.tcl" -tclargs "$OUT"
vivado -mode batch -source "$here/impl_b.tcl" -tclargs "$OUT"

# The GPIO fields by name, beside the bitstream they describe: the bench
# scripts read every bit through it.
cp "$OUT/generated/gpio_layout.json" "$OUT/out/gpio_layout.json"
cp "$OUT/generated/address_map.json" "$OUT/out/address_map.json"
# the fabric clocks load.py sets before it programs the fabric
cp "$OUT/generated/clocks.json" "$OUT/out/clocks.json"

echo
echo "artifacts: $OUT/out/rx.bit, gpio_layout.json, address_map.json and clocks.json"
echo "NEXT: if the picture sits displaced, measure the write-side skew"
echo "-- it re-rolls per link lock. See the README, 'After the build'."
